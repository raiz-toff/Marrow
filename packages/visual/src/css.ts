/**
 * The class-driven stylesheet for the hero (SVG) tier, generated from the same
 * tables and rule list the canvas folds. Colours are only ever `var(--…)`
 * references to `themeVars` (ADR-0013); px metrics come from the spec tables.
 */
import { edgeCss, motionOffCss } from './rules.js';
import { CHIP, EDGE_OPACITY, FLOW_SECONDS, PILL, STATUSES } from './spec.js';
import { FLOW_PERIOD_VAR } from './tokens.js';

const FLOW_ANIMATION = `mFlow ${FLOW_SECONDS}s linear infinite`;

function build(): string {
  const base = 'fill: none; stroke-linejoin: round; transition: opacity .25s; cursor: pointer';
  return [
    '/* ── edges (generated by @marrow/visual: base → speed → mode → flow → status → state) ── */',
    edgeCss(FLOW_ANIMATION, base),
    `.m-edge-rail { fill: none; stroke: var(--bg); stroke-width: var(--edge-width-slot); stroke-linejoin: round; opacity: ${EDGE_OPACITY.base}; cursor: pointer; }`,
    `:where(:root[data-zoom="far"]) .m-edge-rail.m-leaf { opacity: ${EDGE_OPACITY.far}; }`,
    `.focus-mode .m-edge-rail { opacity: ${EDGE_OPACITY.dimmed}; }`,
    `.focus-mode .m-edge.is-path + .m-edge-rail { opacity: ${EDGE_OPACITY.path}; }`,
    '.m-edge-hit { fill: none; stroke: transparent; stroke-width: 16px; stroke-linejoin: round; cursor: pointer; pointer-events: stroke; }',
    '',
    '/* draw-in: px dashes sized by the path\'s own --len; stops matching once settled,',
    '   so status / mode / flow dashes take over with no reset rule */',
    '@media (prefers-reduced-motion: no-preference) {',
    '  :root:not(.settled) .m-edges .m-edge, :root:not(.settled) .m-edges .m-edge-rail {',
    '    stroke-dasharray: calc(var(--len) * 1px) calc(var(--len) * 1px); stroke-dashoffset: calc(var(--len) * 1px);',
    '    animation: mDraw .55s ease-out .7s both;',
    '  }',
    '}',
    '@keyframes mDraw { to { stroke-dashoffset: 0; } }',
    `@keyframes mFlow { from { stroke-dashoffset: var(${FLOW_PERIOD_VAR}); } to { stroke-dashoffset: 0; } }`,
    '/* motion off: flow drops its dash; mode/status dashes come back from the same list */',
    motionOffCss(':root[data-motion="off"] '),
    '@media (prefers-reduced-motion: reduce) {',
    motionOffCss(''),
    '}',
    '',
    '/* ── nodes ── */',
    '.m-node { cursor: pointer; outline: none; transition: opacity .25s; }',
    `.m-chip { fill: var(--chip); stroke: var(--chip-line); stroke-width: ${CHIP.ringWidth}; transition: stroke .15s, stroke-width .15s; }`,
    '.m-node:hover .m-chip, .m-node:focus-visible .m-chip, .m-node.is-focus .m-chip { stroke: var(--ink-dim); }',
    `.m-node.m-hero .m-chip { stroke: var(--ring); stroke-width: ${CHIP.heroWidth}; }`,
    '.is-search-active .m-node.is-search-match .m-chip { stroke: var(--ring); }',
    `.m-node.is-selected .m-chip { stroke: var(--ring); stroke-width: ${CHIP.selectedWidth}; }`,
    '.m-led { stroke: var(--bg); stroke-width: 2; }',
    ...STATUSES.map((s) => `.m-status-${s.id} .m-led { fill: var(${s.color}); }`),
    '.m-label { fill: var(--ink); font-size: 12px; paint-order: stroke; stroke: var(--bg); stroke-width: 3px; transition: opacity .3s; }',
    '.m-icon-fallback { fill: var(--ink-dim); font-size: 18px; font-weight: 600; }',
    `.m-node.m-ghost { opacity: ${CHIP.ghostOpacity}; }`,
    `.m-node.m-ghost .m-chip { stroke-dasharray: ${CHIP.ghostDash.join(' ')}; }`,
    '.m-node.m-ghost:hover { opacity: .9; }',
    `.focus-mode .m-node:not(.is-focus):not(.is-adj):not(.is-selected) { opacity: ${CHIP.dimOpacity}; }`,
    ':root[data-zoom="far"] .m-label { opacity: 0; }',
    '',
    '/* aggregate badges (device counts, stacks) */',
    '.m-badge rect { fill: var(--m-accent); stroke: var(--bg); stroke-width: 2; }',
    `.m-badge text { fill: var(--m-accent-ink); font-size: ${PILL.badge.fontPx}px; font-weight: 700; }`,
    '',
    '/* edge aggregate labels (×24) */',
    '.m-edge-label { cursor: pointer; }',
    '.m-edge-label rect { fill: var(--bg); stroke: var(--line-strong); stroke-width: 1; }',
    `.m-edge-label text { fill: var(--ink); font-size: ${PILL.label.fontPx}px; font-weight: 700; }`,
    '',
    '/* semantic link chips — VLANs / encap / protocol / lag, with an optional glyph */',
    '.m-edge-chip { cursor: pointer; }',
    '.m-edge-chip > rect { fill: var(--bg); stroke: var(--line-strong); stroke-width: 1; }',
    `.m-edge-chip > text { fill: var(--ink); font-size: ${PILL.chip.fontPx}px; font-weight: 600; letter-spacing: .01em; }`,
    '.m-chip-glyph { fill: var(--ink-dim); }',
    '.m-chip-glyph path { fill: none; stroke: var(--ink-dim); stroke-width: 1.3; stroke-linecap: round; stroke-linejoin: round; }',
    '.m-chip-glyph-stroke path { fill: none; stroke: var(--ink-dim); stroke-width: 1.3; stroke-linecap: round; }',
    '/* the VPN/tunnel chip is tinted so the padlock reads as "secure overlay" */',
    '.m-edge-chip[data-glyph="lock"] > rect { stroke: color-mix(in srgb, var(--m-accent) 50%, var(--line-strong)); }',
    '.m-edge-chip[data-glyph="lock"] .m-chip-glyph { fill: color-mix(in srgb, var(--m-accent) 70%, var(--ink-dim)); }',
  ].join('\n');
}

let cached: string | undefined;

/** The visual-language stylesheet (edges, nodes, chips, state rules, keyframes). */
export function visualCss(): string {
  return (cached ??= build());
}
